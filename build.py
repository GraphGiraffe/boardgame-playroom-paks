#!/usr/bin/env python3
"""Собрать переносимые паки Playroom: JSON, коллекцию ZIP и исходники."""

import argparse
import base64
import hashlib
import json
import mimetypes
from pathlib import Path, PurePosixPath
import re
import zipfile


ROOT = Path(__file__).resolve().parent

# Both repositories execute the same pinned compiler; plugins are trusted code.
_compiler_path = ROOT / "shared/pack_compiler.py"
_compiler = {"__file__": str(_compiler_path)}
exec(compile(_compiler_path.read_text(encoding="utf-8"), str(_compiler_path), "exec"), _compiler)
json_text = _compiler['json_text']
parse_json = _compiler['parse_json']
path_ok = _compiler['path_ok']
number_equals = _compiler['number_equals']
js_trim = _compiler['js_trim']
validate_manifest = _compiler['validate_manifest']
validate_asset = _compiler['validate_asset']
validate_bundle = _compiler['validate_bundle']
local_file = _compiler['local_file']
read_manifest = _compiler['read_manifest']
pack_files = _compiler['pack_files']
bundle_source_modules = _compiler['bundle_source_modules']
build_pack = _compiler['build_pack']
MAX_PACK_BYTES = _compiler['MAX_PACK_BYTES']
MAX_PACK_FILES = _compiler['MAX_PACK_FILES']
TEXT_EXTENSIONS = _compiler['TEXT_EXTENSIONS']
ENTRY_POINTS = _compiler['ENTRY_POINTS']
SEMVER = _compiler['SEMVER']
VERSION = "0.8.9-preview.54"


def compatibility_manifest(manifest):
    data = json.dumps(manifest, ensure_ascii=False, indent=2)
    key = json.dumps(manifest["id"])
    return ("// Generated by build.py from manifest.json. Edit manifest.json instead.\n"
            "(function (root) {\n  'use strict';\n  root.PlayroomCatalog ||= {};\n"
            f"  root.PlayroomCatalog[{key}] = {data};\n}})(globalThis);\n")


def write_zip(destination, items):
    """Stable timestamps and ordering make repeated builds reproducible."""
    with zipfile.ZipFile(destination, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, content in sorted(items):
            info = zipfile.ZipInfo(name, (2020, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = (0o100755 if name.endswith(".sh") else 0o100644) << 16
            archive.writestr(info, content)


def source_files(packs):
    result = {ROOT / "build.py", ROOT / "build.sh"}
    for name in ("README.md", ".gitignore", ".gitattributes", ".nvmrc", "AGENTS.md", "CONTRIBUTING.md", "CHANGELOG.md"):
        if (ROOT / name).is_file():
            result.add(ROOT / name)
    for pattern in ("docs/**/*.md", "docs/design/**/*.jpg", "docs/design/**/*.png", "scripts/*.py", "scripts/codex/*.sh", ".github/workflows/*.yml", ".github/workflows/*.yaml", "tests/*.cjs"):
        result.update(ROOT.glob(pattern))
    # Ship runnable authoring examples in the source archive without adding
    # them to the installable game collection.
    result.update(path for path in (ROOT / "examples").rglob("*") if path.is_file())
    result.update(path for path in (ROOT / "shared").rglob("*") if path.is_file() and "__pycache__" not in path.parts)
    for pack in packs:
        manifest = read_manifest(pack)
        result.update(pack_files(pack, manifest))
        result.update(pack / name for name in ("manifest.json", "manifest.js"))
    for path in sorted(result):
        if path.is_symlink() or not path.is_file() or not path.resolve().is_relative_to(ROOT):
            raise ValueError(f"Неподдерживаемый исходный файл: {path}")
        yield path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=ROOT / "dist", help="Каталог результата (по умолчанию: dist/ рядом со скриптом)")
    parser.add_argument("--include-examples", action="store_true", help="Дополнительно собрать учебные примеры из examples/")
    args = parser.parse_args()
    packs = sorted(path.parent for path in (ROOT / "packs").glob("*/manifest.json"))
    if not packs:
        parser.error("В packs/ не найдено manifest.json")
    if args.include_examples:
        packs += sorted(path.parent for path in (ROOT / "examples").glob("*/manifest.json"))
    bundles = [build_pack(pack) for pack in packs]
    output = args.output_dir.resolve()
    output.mkdir(parents=True, exist_ok=True)
    artifacts = []
    for pack, bundle in zip(packs, bundles):
        wrapper = compatibility_manifest(bundle["manifest"])
        target = pack / "manifest.js"
        if not target.is_file() or target.read_text(encoding="utf-8") != wrapper:
            target.write_text(wrapper, encoding="utf-8")
        destination = output / f"{bundle['manifest']['id']}-{bundle['manifest']['version']}.playroom-pack.json"
        destination.write_text(json_text(bundle), encoding="utf-8")
        artifacts.append(destination)
    collection = output / f"playroom-paks-{VERSION}.zip"
    write_zip(collection, [(path.name, path.read_bytes()) for path in artifacts])
    source = output / "playroom-paks-source.zip"
    write_zip(source, [("playroom-paks/" + path.relative_to(ROOT).as_posix(), path.read_bytes()) for path in source_files(packs)])
    artifacts.extend([collection, source])
    # Keep authoring masters in source_files(), never in installable assets.
    asset_manifests = sorted((ROOT / "shared/asset-packs").glob("*/manifest.json"))
    source_art = {manifest.parent / item["source"] for manifest in asset_manifests
                  for item in json.loads(manifest.read_text(encoding="utf-8")).get("items", [])
                  if item.get("source")}
    asset_sources = sorted(path for folder in ("assets", "components", "templates", "sounds", "locales", "domain", "asset-packs")
                           for path in (ROOT / "shared" / folder).rglob("*") if path.is_file() and path not in source_art)
    asset_archive = output / f"playroom-shared-assets-{VERSION}.zip"
    write_zip(asset_archive, [(path.relative_to(ROOT / "shared").as_posix(), path.read_bytes()) for path in asset_sources])
    artifacts.append(asset_archive)
    for manifest_path in asset_manifests:
        spec = json.loads(manifest_path.read_text(encoding="utf-8"))
        archive = output / f"playroom-assets-{spec['id']}-{spec['version']}.zip"
        write_zip(archive, [(path.relative_to(manifest_path.parent).as_posix(), path.read_bytes()) for path in sorted(manifest_path.parent.rglob("*")) if path.is_file() and path not in source_art])
        artifacts.append(archive)
    checksums = output / "SHA256SUMS"
    checksums.write_text("".join(f"{hashlib.sha256(path.read_bytes()).hexdigest()}  {path.name}\n" for path in sorted(artifacts)), encoding="ascii")
    print(f"Паки: {len(bundles)} файлов *.playroom-pack.json в {output}")
    print(f"Коллекция: {collection.name}; ассеты: {asset_archive.name}; исходники: {source.name}; контрольные суммы: {checksums.name}")
    print("В Playroom откройте управление играми и выберите нужные JSON-файлы паков.")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError) as error:
        raise SystemExit(f"Ошибка сборки: {error}") from error
